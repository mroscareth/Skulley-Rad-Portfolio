// Bolsas sin repetir hasta acabarlas, por idioma y por lista.
const bolsas = {}
export function sacarAlien(lang, lista) {
  const L = lang === 'en' ? 'en' : 'es'
  const fuente = DIALOGO_ALIEN[L][lista] || []
  const k = `${L}|${lista}`
  if (!bolsas[k]?.length) bolsas[k] = fuente.map((_, i) => i).sort(() => Math.random() - 0.5)
  return fuente[bolsas[k].shift()]
}
